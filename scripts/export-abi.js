// Copies the compiled ABI into the frontend after `npm run compile`
const fs = require("fs");
const path = require("path");
const art = require("../artifacts/contracts/MilestonePay.sol/MilestonePay.json");
fs.writeFileSync(
  path.join(__dirname, "..", "frontend", "abi.js"),
  `// Auto-generated by scripts/export-abi.js\nwindow.MILESTONEPAY_ABI = ${JSON.stringify(art.abi, null, 2)};\n`
);
console.log("frontend/abi.js updated");
